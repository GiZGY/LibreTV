import fs from 'node:fs';
import vm from 'node:vm';
import assert from 'node:assert/strict';
const source=fs.readFileSync(new URL('../web/live-ui.js',import.meta.url),'utf8');
const rank=source.slice(source.indexOf('  function rankedLines(f)'),source.indexOf('  function routeButtons(f)'));
const remember=source.slice(source.indexOf('  function rememberLinePosition(f,video)'),source.indexOf('  const failedPlaybackLines='));
const start=source.indexOf('    failed(media){');
const method=source.slice(start,source.indexOf('\n  };',start));
const media={filmId:'film',lineKey:'a',episode:2};
const film={id:'film',lineIndex:0,lines:[{key:'a',health:'fast',episodes:['1','2']},{key:'missing',health:'fast',episodes:['1']},{key:'b',health:'fair',episodes:['1','2']}]};
const video={currentTime:500,duration:1000};
let renders=0,saves=0;const notices=[];
const ctx={activePlayback:media,films:[film],failedPlaybackLines:new Map(),historyMetadata:{},document:{querySelector:()=>video},toast:s=>notices.push(s),render:()=>renders++};
vm.createContext(ctx);vm.runInContext(rank+remember+'\nvar lineTransfer,continuePlayback=false;var LivePlayback={'+method+',progress(){}};',ctx);
ctx.LivePlayback.progress=()=>saves++;
ctx.LivePlayback.failed({...media});assert.equal(renders,0,'stale callback must not switch');
ctx.LivePlayback.failed(media);assert.equal(renders,1);assert.equal(saves,1);assert.equal(film.lineIndex,2,'skip alternatives missing current episode');
assert.equal(ctx.lineTransfer.ratio,.5);assert.equal(ctx.lineTransfer.episode,2);
ctx.LivePlayback.failed(media);assert.equal(renders,1,'duplicate errors must not trigger repeated renders');
const replacement={...media,lineKey:'b'};ctx.activePlayback=replacement;
ctx.LivePlayback.failed(media);assert.equal(renders,1,'old player errors cannot affect replacement');
ctx.LivePlayback.failed(replacement);assert.equal(renders,1,'exhaustion does not cycle to failed lines');
assert.ok(notices.at(-1).includes('播放暂时失败'));
ctx.activePlayback={...media,episode:1};ctx.LivePlayback.failed(ctx.activePlayback);assert.equal(renders,2,'another episode has independent failure state');
assert.equal(film.lineIndex,1);
console.log('New UI fallback: stale/duplicate events, episode availability, ratio resume, exhaustion and episode isolation passed');
