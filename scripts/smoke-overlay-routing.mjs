import fs from 'node:fs';
import vm from 'node:vm';
import assert from 'node:assert/strict';
const source=fs.readFileSync(new URL('../web/live-ui.js',import.meta.url),'utf8');
const method=source.slice(source.indexOf('    overlay(media){'),source.indexOf('    continue(){'));
const media={filmId:'film',lineKey:'line',episode:1};
const ctx={activePlayback:media,overlayNotifiedPlayback:new WeakSet()};
vm.createContext(ctx);vm.runInContext('var playback={'+method+'};',ctx);
assert.equal(ctx.playback.overlay({...media}),false,'ignore stale callbacks');
assert.equal(ctx.playback.overlay(media),true,'first evidence triggers brief warning');
assert.equal(ctx.playback.overlay(media),false,'multiple fingerprints do not repeat warning');
ctx.activePlayback={...media,episode:2};
assert.equal(ctx.playback.overlay(ctx.activePlayback),true,'new playback can warn once');
assert.doesNotMatch(method,/render\(|lineIndex|currentTime|rankedLines|toast\(/,'overlay must not interrupt playback or switch lines');
const player=fs.readFileSync(new URL('../web/player-preview.js',import.meta.url),'utf8');
assert.match(player,/请勿相信片中广告/);
assert.match(player,/overlayTimer=setTimeout\([\s\S]*?2000\)/);
assert.match(player,/clearTimeout\(overlayTimer\);overlayNotice\?\.remove\(\)/);
console.log('Overlay warning: stale callbacks, deduplication, no switching, 2-second dismissal and teardown passed');
